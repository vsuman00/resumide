const runtime = Object.freeze({
  node: "v22.23.4",
  unicode: "17.0",
  icu: "78.3",
  v8: "12.4.254.21-node.57",
});
const actual = {
  node: process.version,
  unicode: process.versions.unicode,
  icu: process.versions.icu,
  v8: process.versions.v8,
};
if (Object.keys(runtime).some((key) => actual[key] !== runtime[key]))
  throw Error("JD_UNICODE_RUNTIME_UNSUPPORTED");
const args = process.argv.slice(2);
if (args.length !== 1 || !["--write", "--check"].includes(args[0]))
  throw Error("Use --write or --check");
const started = performance.now();
const target = new URL(
  "../app/lib/server/job-relation-unicode.ts",
  import.meta.url,
);
const digest = (value) =>
  createHash("sha256").update(JSON.stringify(value)).digest("hex");
const rules = {
  identifier: "Unicode General_Category Letter, Number or Mark",
  aliasExtras: [36, 95],
  aliasDot: "leading denied; trailing denied only before an identifier or _$",
  durationLeftExtras: [44, 46, 95],
  durationRightExtras: [95],
  whitespace: "ECMAScript /^\\s$/u; trim uses the same scalar set",
  regexWordIu: "ECMAScript /^\\w$/iu",
  defaultLower:
    "Isolated-scalar String.prototype.toLowerCase; no normalization",
  regexAsciiFold: "ECMAScript /^a$/iu through /^z$/iu equivalence",
  finalSigma: "Default Unicode SpecialCasing Final_Sigma context",
  input: "Reject NUL and unpaired surrogates; preserve all other raw scalars",
  offsets: "Unicode code points; size limits count UTF16 code units",
};
const data = {
  identifierRanges: [],
  casedRanges: [],
  caseIgnorableRanges: [],
  regexWordIuRanges: [],
  whitespaceRanges: [],
  defaultLowerMappings: [],
  regexAsciiFoldMappings: [],
  finalSigma: {
    codePoint: 931,
    defaultLower: 963,
    finalLower: 962,
    before: "preceded-by-Cased-ignoring-Case_Ignorable",
    after: "not-followed-by-Cased-ignoring-Case_Ignorable",
  },
};
const properties = [
  ["identifierRanges", /^[\p{L}\p{N}\p{M}]$/u],
  ["casedRanges", /^\p{Cased}$/u],
  ["caseIgnorableRanges", /^\p{Case_Ignorable}$/u],
  ["regexWordIuRanges", /^\w$/iu],
  ["whitespaceRanges", /^\s$/u],
];
const asciiLetters = Array.from({ length: 26 }, (_, index) => [
  97 + index,
  new RegExp(`^${String.fromCharCode(97 + index)}$`, "iu"),
]);
const appendRange = (ranges, codepoint) => {
  const last = ranges.at(-1);
  if (last && last[1] + 1 === codepoint) last[1] = codepoint;
  else ranges.push([codepoint, codepoint]);
};
let scalarCount = 0;
for (let codepoint = 0; codepoint <= 0x10ffff; codepoint++) {
  if ((codepoint & 4095) === 0 && performance.now() - started > 55_000)
    throw Error("JD_UNICODE_GENERATION_DEADLINE");
  if (codepoint >= 0xd800 && codepoint <= 0xdfff) continue;
  scalarCount++;
  const scalar = String.fromCodePoint(codepoint);
  for (const [name, pattern] of properties)
    if (pattern.test(scalar)) appendRange(data[name], codepoint);
  const lower = scalar.toLowerCase();
  if (lower !== scalar)
    data.defaultLowerMappings.push([
      codepoint,
      Array.from(lower, (character) => character.codePointAt(0)),
    ]);
  if (/^[a-z]$/iu.test(scalar)) {
    const matches = asciiLetters.filter(([, pattern]) => pattern.test(scalar));
    if (matches.length !== 1) throw Error("JD_UNICODE_FOLD_NOT_UNIQUE");
    data.regexAsciiFoldMappings.push([codepoint, matches[0][0]]);
  }
}
const profile = {
  schemaVersion: "jd-unicode-profile/1.0.0",
  runtime,
  rules,
  ruleSha256: digest(rules),
  dataSha256: digest(data),
  scalarCount,
  data,
};
const profileHash = digest(profile);
const inline = (value) => JSON.stringify(value).replaceAll(",", ", ");
const renderObject = (value, indent = 0) => {
  const padding = " ".repeat(indent);
  return `{
${Object.entries(value)
  .map(([key, item]) => {
    const rendered = Array.isArray(item)
      ? item.every((row) => !Array.isArray(row))
        ? inline(item)
        : `[\n${item.map((row) => `${padding}    ${inline(row)},`).join("\n")}\n${padding}  ]`
      : item !== null && typeof item === "object"
        ? renderObject(item, indent + 2)
        : JSON.stringify(item);
    const line = `${padding}  ${key}: ${rendered},`;
    return !rendered.includes("\n") && line.length > 80
      ? `${padding}  ${key}:\n${padding}    ${rendered},`
      : line;
  })
  .join("\n")}
${padding}}`;
};
