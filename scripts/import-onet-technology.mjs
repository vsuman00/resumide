// Builds app/lib/server/matching/onet-technology.generated.ts from the O*NET 31.0 database file
// software_skills.csv (CC BY 4.0, see ONET_ATTRIBUTION in vocabulary.ts). Owner decision ATS-D1.
// Usage: node scripts/import-onet-technology.mjs <path-to-software_skills.csv>
// Keeps only tools O*NET flags "Hot Technology", so the list stays small and reviewable.
import { readFileSync, writeFileSync } from "node:fs";

const input = process.argv[2];
if (!input) throw new Error("Pass the path to software_skills.csv");

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      field = "";
      if (row.length > 1 || row[0] !== "") rows.push(row);
      row = [];
    } else field += c;
  }
  if (field || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

const [header, ...rows] = parseCsv(
  readFileSync(input, "utf8").replace(/^\uFEFF/, ""),
);
const example = header.indexOf("Workplace Example");
const hot = header.indexOf("Hot Technology");
if (example < 0 || hot < 0) throw new Error("Unexpected O*NET columns");

const VENDORS = [
  "Microsoft",
  "Adobe",
  "Autodesk",
  "Oracle",
  "Google",
  "The MathWorks",
  "Atlassian",
  "Amazon",
  "Apple",
  "IBM",
  "Salesforce",
];
const names = [
  ...new Set(
    rows
      .filter((r) => r[hot] === "Y")
      .map((r) => r[example].trim())
      .filter((name) => name.length > 1),
  ),
].sort((a, b) => a.localeCompare(b, "en"));

const entries = names.map((name) => {
  const withoutSoftware = name.replace(/\s+software$/i, "");
  const vendor = VENDORS.find((v) => withoutSoftware.startsWith(`${v} `));
  const bare = vendor
    ? withoutSoftware.slice(vendor.length + 1)
    : withoutSoftware;
  const aliases = [withoutSoftware, bare].filter(
    (alias, i, all) =>
      alias.length > 2 && alias !== name && all.indexOf(alias) === i,
  );
  return { canonical: name, aliases };
});

const body = entries
  .map(
    (e) =>
      `  { canonical: ${JSON.stringify(e.canonical)}, aliases: ${JSON.stringify(e.aliases)} },`,
  )
  .join("\n");
writeFileSync(
  new URL(
    "../app/lib/server/matching/onet-technology.generated.ts",
    import.meta.url,
  ),
  `// Generated by scripts/import-onet-technology.mjs from the O*NET 31.0 Database (CC BY 4.0).
// Do not edit by hand. Hot-technology tool names only; aliases drop the vendor and "software".
export const ONET_TECHNOLOGY: readonly {
  canonical: string;
  aliases: readonly string[];
}[] = [
${body}
];
`,
);
console.log(`Wrote ${entries.length} entries`);
